// Feedback describes a possible check suggested by the submitted value.
// It does not infer the learner's ability or print a worked answer.
export function quizFeedback(question, submittedValue) {
  const feedback=question.feedback;
  if(!feedback)return '可先核对题目给定的输入与计算规则，再分层查看提示或重试。';
  const key=question.type==='number'?String(Number(submittedValue)):String(submittedValue);
  return Object.hasOwn(feedback.byValue,key)?feedback.byValue[key]:feedback.check;
}
